-- Run in Snowsight as an administrator. Creates Klane-only resources.
-- The warehouse stays suspended until used, then suspends after 60 idle seconds.
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS KLANE_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS KLANE;
CREATE SCHEMA IF NOT EXISTS KLANE.PUBLIC;
CREATE ROLE IF NOT EXISTS KLANE_APP;
USE DATABASE KLANE;
USE SCHEMA PUBLIC;
CREATE TABLE IF NOT EXISTS KLANE_SIGNAL_EVENTS (
 ACCOUNT_ID VARCHAR, EVENT_ID VARCHAR, SIGNAL_ID VARCHAR, COMPANY_ID VARCHAR,
 OBSERVED_AT TIMESTAMP_TZ, COLLECTED_AT TIMESTAMP_TZ, CITY VARCHAR,
 SERVICE VARCHAR, KIND VARCHAR, STATUS VARCHAR, CONFIDENCE FLOAT, SOURCE_URL VARCHAR
);
CREATE TABLE IF NOT EXISTS KLANE_JOB_COMPARABLES (
 JOB_ID VARCHAR, CITY VARCHAR, SERVICE VARCHAR, UNIT VARCHAR, SCOPE_CLASS VARCHAR,
 COMPLETED_AT DATE, UNITS FLOAT, CONTRACT_VALUE FLOAT, DIRECT_COST FLOAT,
 SOURCE_URL VARCHAR, VERIFIED BOOLEAN
);
GRANT USAGE ON WAREHOUSE KLANE_WH TO ROLE KLANE_APP;
GRANT USAGE ON DATABASE KLANE TO ROLE KLANE_APP;
GRANT USAGE ON SCHEMA KLANE.PUBLIC TO ROLE KLANE_APP;
GRANT SELECT, INSERT, UPDATE ON TABLE KLANE.PUBLIC.KLANE_SIGNAL_EVENTS TO ROLE KLANE_APP;
GRANT SELECT, INSERT, UPDATE ON TABLE KLANE.PUBLIC.KLANE_JOB_COMPARABLES TO ROLE KLANE_APP;
-- Self-contained block: no worksheet/session variable dependency.
EXECUTE IMMEDIATE $$
DECLARE
  klane_user VARCHAR DEFAULT CURRENT_USER();
  grant_statement VARCHAR;
BEGIN
  grant_statement := 'GRANT ROLE KLANE_APP TO USER "' || REPLACE(klane_user, '"', '""') || '"';
  EXECUTE IMMEDIATE grant_statement;
END;
$$;
